// Builds dist/bundle.lua: compiles src/ with tlua, then packs every emitted module into one
// chunk behind a bundle-local `require` (tlua has no bundler).
//
// The bootstrap runs the bundle with RunString, so it must be a single self-contained file.

import fs from 'node:fs'
import path from 'node:path'
import { Glob } from 'bun'

const root = import.meta.dir
const outDir = path.join(root, 'out')
const bundlePath = path.join(root, 'dist', 'bundle.lua')
const entry = 'main'

fs.rmSync(outDir, { recursive: true, force: true })
const tlua = Bun.spawnSync(['tlua', '-p', root], {
	cwd: root,
	stdout: 'inherit',
	stderr: 'inherit',
})
if (tlua.exitCode !== 0) {
	process.exit(tlua.exitCode ?? 1)
}

// Per-module source rewrites. Each placeholder is replaced in its own module only, so the
// same text elsewhere (a log line) is left alone.
const rewrites: Record<string, (source: string) => string> = {
	meta: (source) =>
		[
			['"$VERSION$"', process.env.DONATOS_ADDON_VERSION],
			['"$BUILD_NUMBER$"', process.env.GITHUB_RUN_NUMBER],
			['"$COMMIT_HASH$"', process.env.GITHUB_SHA],
		].reduce(
			(text, [placeholder, value]) =>
				replaceOnce(text, placeholder as string, luaString(value ?? '')),
			source,
		),
}

const modules = new Map<string, string>()
for (const file of new Glob('**/*.lua').scanSync(outDir)) {
	const name = file.slice(0, -'.lua'.length).split(path.sep).join('.')
	const source = fs.readFileSync(path.join(outDir, file), 'utf8')
	modules.set(name, rewrites[name]?.(source) ?? source)
}

if (!modules.has(entry)) {
	throw new Error(`Entry module "${entry}" was not emitted.`)
}
for (const name of Object.keys(rewrites)) {
	if (!modules.has(name)) {
		throw new Error(`Module "${name}" has a rewrite but was not emitted.`)
	}
}

const parts = [
	'-- Donatos bundle. Generated by lua/main/build.ts; do not edit.',
	'local __modules = {}',
	'local __loaded = {}',
	'local __loading = {}',
	'local __hostRequire = require',
	'local function require(name)',
	'\tlocal cached = __loaded[name]',
	'\tif cached ~= nil then',
	'\t\treturn cached.value',
	'\tend',
	'\tlocal loader = __modules[name]',
	'\tif loader == nil then',
	'\t\treturn __hostRequire(name)',
	'\tend',
	'\tif __loading[name] then',
	'\t\terror("circular require of module \'" .. name .. "\'", 2)',
	'\tend',
	'\t__loading[name] = true',
	'\tlocal value = loader(name)',
	'\t__loading[name] = nil',
	'\t__loaded[name] = { value = value }',
	'\treturn value',
	'end',
]
for (const [name, source] of [...modules].sort(([a], [b]) =>
	a.localeCompare(b),
)) {
	parts.push(
		`__modules[${luaString(name)}] = function(...)`,
		source.trimEnd(),
		'end',
	)
}
parts.push(`return require(${luaString(entry)})`, '')

fs.mkdirSync(path.dirname(bundlePath), { recursive: true })
fs.writeFileSync(bundlePath, parts.join('\n'))
console.log(
	`build: packed ${modules.size} modules into ${path.relative(root, bundlePath)}`,
)

function replaceOnce(
	source: string,
	placeholder: string,
	replacement: string,
): string {
	const index = source.indexOf(placeholder)
	if (index === -1 || source.indexOf(placeholder, index + 1) !== -1) {
		throw new Error(`Expected exactly one ${placeholder} in the module.`)
	}
	return (
		source.slice(0, index) +
		replacement +
		source.slice(index + placeholder.length)
	)
}

function luaString(value: string): string {
	let escaped = ''
	for (const c of value) {
		const code = c.charCodeAt(0)
		if (c === '\\' || c === '"') {
			escaped += `\\${c}`
		} else if (code < 0x20 || code === 0x7f) {
			escaped += `\\${code.toString().padStart(3, '0')}`
		} else {
			escaped += c
		}
	}
	return `"${escaped}"`
}
